// File: scripts/evidence.mjs · Node 22 ESM
// Turns the rows the test suites append to docs/evidence/.rows-<target>.jsonl into the evidence file:
//   docs/evidence/test-matrix-<target>-<date>.md (one row per assertion: id, API, persona, attempt,
//   HTTP/Parse code, body assertion, state assertion).
// Wired into npm: `pretest` runs `--reset`, `posttest` writes the file, so the committed evidence always
// reflects ONE complete `npm test` run. Run dates use the local machine's date.
import { readFileSync, writeFileSync, rmSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { ROOT, args } from './lib/env.mjs';

const EVIDENCE_DIR = path.join(ROOT, 'docs', 'evidence');
// Evidence is labeled by what it actually ran against: 'back4app' only for the real live host.
const TARGET = !process.env.TEST_SERVER_URL ? 'local'
  : /back4app\.com/.test(process.env.TEST_SERVER_URL) ? 'back4app' : 'remote-rehearsal';
const ROWS_FILE = path.join(EVIDENCE_DIR, `.rows-${TARGET}.jsonl`);
const a = args();

if (a.reset) {
  rmSync(ROWS_FILE, { force: true });
  process.exit(0);
}

if (!existsSync(ROWS_FILE)) {
  console.error(`evidence: no .rows-${TARGET}.jsonl — run \`npm test\` first.`);
  process.exit(1);
}

const rows = readFileSync(ROWS_FILE, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
const byId = new Map();
for (const r of rows) byId.set(r.id + '|' + (r.protocol || '') + '|' + (r.attempt || ''), r); // last record of a re-run wins; distinct attempts keep their own rows
const date = new Date().toISOString().slice(0, 10);

const order = (id) => {
  const m = id.match(/^([A-Z]+)(\d+)(.*)$/);
  const series = { G: 0, P: 1, S: 2, C: 3, M: 4 }[m ? m[1] : 'Z'] ?? 9;
  return [series, m ? Number(m[2]) : 999, m ? m[3] : ''];
};
const sorted = [...byId.values()].sort((x, y) => {
  const [a1, a2, a3] = order(x.id); const [b1, b2, b3] = order(y.id);
  return a1 - b1 || a2 - b2 || (a3 < b3 ? -1 : a3 > b3 ? 1 : 0) || (x.protocol || '').localeCompare(y.protocol || '');
});

const esc = (s) => String(s ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');

writeFileSync(path.join(EVIDENCE_DIR, `test-matrix-${TARGET}-${date}.md`), `# Test matrix — ${TARGET.toUpperCase()} run, ${date}

Generated by \`npm test\` (scripts/evidence.mjs) from a single complete run against ${TARGET === 'local'
    ? 'an in-process parse-server (PostgreSQL adapter, port 5433, database `gql_test`) with the auto-generated GraphQL API mounted at /graphql. **Local evidence only** — local GraphQL availability says nothing about the live plan; Phase 0 owns the live story.'
    : 'the live backend (coordinator-run phase).'} Every assertion checks the response body AND, where state
changes, the database state (master-key read-back) — not just the status code. GraphQL rows treat an \`errors\`
array or partial \`data\` as a failure even on HTTP 200.

| # | API | Persona | Attempt | HTTP / code | Body assertion | State assertion |
|---|---|---|---|---|---|---|
${sorted.map((r) => `| ${r.id} | ${esc(r.protocol)} | ${esc(r.persona)} | ${esc(r.attempt)} | ${esc(r.status)} · ${esc(r.code)} | ${esc(r.body)} | ${esc(r.state)} |`).join('\n')}

Suites in this run: ${[...new Set(sorted.map((r) => r.suite))].join(', ')} · ${sorted.length} rows recorded at ${new Date().toISOString()}.

## Live-only numbers (not quoted from local runs, by design)

| What | Why live-only |
|---|---|
| M1–M5 headline wall times on Back4app | the published latency numbers must come from the platform the article is about; local wall times are loopback-only harness proof |
| Live GraphQL availability, headers, introspection posture | Phase 0 (coordinator). One datapoint exists (2026-11-03 probe, see build diary); CLP/ACL/session parity and cursor format on the LIVE endpoint are still unverified |
| Plan metering of /batch and multi-operation GraphQL POSTs | only the live Plan Usage page can answer it (and it lags ~a day) — budget inventory carries both columns until then |
`);

console.log(`evidence: wrote test-matrix-${TARGET}-${date}.md (${sorted.length} rows)`);
for (const f of readdirSync(EVIDENCE_DIR).filter((f) => !f.startsWith('.')).sort()) console.log(`  docs/evidence/${f}`);
